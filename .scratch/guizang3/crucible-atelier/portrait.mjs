import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const BASE = 'http://localhost:8628/crucible-atelier/';
const OUT = '/mnt/tos/workspace/.scratch/guizang3/crucible-atelier';
const b = await chromium.launch({ headless: true, executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox', '--use-gl=swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
const p = await ctx.newPage();
const errs = [], warns = [], perrs = [];
p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); if (m.type() === 'warning') warns.push(m.text()); });
p.on('pageerror', e => perrs.push(String(e)));
await p.goto(BASE, { waitUntil: 'load' });
await p.waitForTimeout(700);
await p.screenshot({ path: `${OUT}/portrait-title.png` });
await p.tap('#startbtn');
await p.waitForTimeout(400);
await p.evaluate(`(() => {
  const G = window.G; G.setNoAuto(true); G.startGame(true); G.setPrestige(2);
  G.setLineLevel(0,6); G.setLineLevel(1,5); G.setLineLevel(2,4); G.setLineLevel(3,3);
  G.setRes({mat: 3680, gold: 12400, ess: 860});
  G.setDiscovered(['mist','mire','soot','dew','ember','lichen','vapor','mudcake','lye','sprout','charcoal','salt','clay','fog','tincture','lime','alkali','resin','glass','broth','pigment','oil']);
  ['water','ash','mist','mire','dew','ember','lichen','vapor','lye','sprout','charcoal','salt','clay','fog','tincture','glass','broth','pigment','oil','resin'].forEach(id=>G.grantItem(id,6));
  G.setPressure(34); G.selectRecipe('resin'); G.step(80); G.craft('resin'); G.step(8);
  const t=document.getElementById('toast'); if(t)t.classList.remove('show');
})()`);
await p.waitForTimeout(300);
await p.screenshot({ path: `${OUT}/portrait-play.png` });
const sc = await p.evaluate('({cx:G.renderer.scene.cx,cy:G.renderer.scene.cy,s:G.renderer.scene.s})');
const w0 = await p.evaluate('G.itemCount("water")');
await p.tap('#gatherbtn');
await p.waitForTimeout(120);
const w1 = await p.evaluate('G.itemCount("water")');
console.log('scene', sc, 'gather', w0, w1);
console.log('errors', errs, warns, perrs);
await b.close();
