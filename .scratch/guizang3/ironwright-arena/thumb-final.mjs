import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({headless:true,executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--use-gl=swiftshader']});
const p = await b.newPage({viewport:{width:1280,height:720}});
const errs=[]; p.on('pageerror',e=>errs.push(String(e))); p.on('console',m=>{if(['error','warning'].includes(m.type()))errs.push(m.type()+':'+m.text())});
await p.goto('http://localhost:8626/ironwright-arena/'); await p.waitForFunction('window.G');
await p.click('#startbtn'); await p.waitForTimeout(250);
await p.evaluate(()=>{ G.selectPart('weapon','cleaver'); G.selectPart('armor','heavy'); G.selectPart('thruster','turbo'); });
await p.click('#confirmBtn'); await p.waitForTimeout(3000);
await p.keyboard.down('KeyW'); await p.waitForTimeout(850); await p.keyboard.up('KeyW');
await p.evaluate(()=>{G.setAimAtBoss(); G.setBossHp(1850); G.setCore(100); G.setPlayerHp(160); G.forceBossAttack('radial');});
await p.waitForTimeout(980);
await p.evaluate(()=>{G.setAimAtBoss(); G.triggerBarrier(); G.fireOnce();});
await p.waitForTimeout(80);
await p.screenshot({path:'thumb-final-1280.png'});
console.log('errors',errs);
console.log(await p.evaluate(()=>G.state()));
await b.close();
