import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({ headless: true, executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox', '--use-gl=swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('pageerror', e => console.log('PAGEERR', String(e)));
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('CONSOLE', m.type(), m.text()); });
await p.goto('http://127.0.0.1:8629/twin-tempo-arena/');
await p.waitForFunction('window.G && window.G.state');
const out = await p.evaluate(() => {
  const G = window.G;
  G.setNoAuto(true);
  const log = [];
  const snap = (tag) => log.push({ tag, ...JSON.parse(JSON.stringify(G.state())) });
  // block test
  G.startMatch('local','medium'); G.setPhase('live');
  G.setFighter('p1',{x:480-30,facing:1,atkCd:0});
  G.setFighter('p2',{x:480+20,hp:100,blocking:false,stunT:0,z:0});
  G.press('KeyF'); G.upd(1);
  log.push({tag:'afterFirstHit', p1: G.state().p1, p2: G.state().p2});
  G.setFighter('p2',{hp:100,blocking:true,stunT:0,vx:0,facing:-1});
  G.clearFx();
  G.press('KeyL'); G.upd(1);
  log.push({tag:'afterBlockFrame', p2: G.state().p2, p1: G.state().p1});
  G.setFighter('p1',{x:480-30,facing:1,atkCd:0});
  G.press('KeyF'); G.upd(1);
  log.push({tag:'afterBlockedAttack', p2: G.state().p2, p1: G.state().p1, hitstop: G.state().lastAttack});
  G.release('KeyL');
  // capture
  G.startMatch('local','medium'); G.startRound(1); G.setPhase('live');
  G.setFighter('p1',{x:480,progress:0,z:0,vx:0});
  G.setFighter('p2',{x:480+240,progress:0,vx:0});
  G.upd(60);
  log.push({tag:'captureAfter60', p1p:G.state().p1.progress, p2p:G.state().p2.progress, p1:G.state().p1, p2:G.state().p2});
  G.setFighter('p2',{x:480+20,vx:0});
  const before = G.state().p1.progress;
  G.upd(10);
  log.push({tag:'captureContested10', before, changed:G.state().p1.progress, contested:G.state().contested, p2x:G.state().p2.x, p2z:G.state().p2.z, p2ground:G.state().p2.onGround, p2stun:G.state().p2.stunT, p2fall:G.state().p2.fallen});
  // dash
  G.startMatch('local','medium'); G.startRound(2); G.setPhase('live'); G.setRoundHalf(255);
  G.setFighter('p1',{x:480-22,z:0,vx:0});
  G.setFighter('p2',{x:480+12,z:0,vx:0,hp:100});
  G.setFighter('p1',{dashT:.18,dashCd:.95,invulnT:.16,vx:790,facing:1});
  log.push({tag:'preDash', p1:G.state().p1, p2:G.state().p2});
  G.upd(1);
  log.push({tag:'postDash', lastImpulse:G.state().lastImpulse, lastDash:G.state().lastDash, p1:G.state().p1, p2:G.state().p2});
  return log;
});
console.log(JSON.stringify(out, null, 2));
await b.close();
