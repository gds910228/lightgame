import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({ headless: true, executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox','--use-gl=swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs=[], reqs=[];
p.on('console', m => { if (['error','warning'].includes(m.type())) errs.push(m.type()+': '+m.text()); });
p.on('pageerror', e => errs.push('pageerror: '+e));
p.on('request', r => reqs.push(r.url()));
await p.goto('http://localhost:8624/glyphbeast-trail/', { waitUntil: 'load' });
await p.waitForTimeout(1200);
console.log('no-param errors', errs);
console.log('state', await p.evaluate(() => window.__G ? {mode: window.__G.state().mode, err: window.__G.err, nan: window.__G.state().nan} : null));
console.log('screenshot...');
await p.screenshot({ path: '/mnt/tos/workspace/.scratch/guizang3/glyphbeast-trail/title-first.png' });
const p2 = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs2=[];
p2.on('console', m => { if (['error','warning'].includes(m.type())) errs2.push(m.type()+': '+m.text()); });
p2.on('pageerror', e => errs2.push('pageerror: '+e));
await p2.goto('http://localhost:8624/glyphbeast-trail/?autotest=1', { waitUntil: 'load' });
await p2.waitForFunction('window.__TEST && window.__TEST.done', { timeout: 180000 }).catch(e=>console.log('waitfail', String(e)));
console.log('autotest', await p2.evaluate(() => window.__TEST ? {pass: window.__TEST.pass, fail: window.__TEST.fail, total: window.__TEST.total, failed: (window.__TEST.results||[]).filter(r=>!r.ok), crash: window.__TEST.crash} : null));
console.log('console', errs2);
console.log('external', reqs.filter(u => !u.includes('localhost')));
await b.close();
