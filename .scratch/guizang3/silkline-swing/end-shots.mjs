import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({ headless: true, executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox','--use-gl=swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
const logs=[]; p.on('console',m=>{if(m.type()==='error'||m.type()==='warning')logs.push(m.type()+': '+m.text())}); p.on('pageerror',e=>logs.push('ERR '+e));
await p.goto('http://localhost:8621/silkline-swing/?level=1', { waitUntil:'load' });
await p.evaluate(() => { localStorage.clear(); });
await p.evaluate(() => { G.setShards(3); G.setTime(22.4); G.forceWin(); });
await p.waitForTimeout(200);
await p.screenshot({ path:'/mnt/tos/workspace/.scratch/guizang3/silkline-swing/end-win.png' });
const win = await p.evaluate('G.state()');
const store = await p.evaluate(() => ({ s: localStorage.getItem('sls2.stars'), u: localStorage.getItem('sls2.unlocked'), b: localStorage.getItem('sls2.best'), t: localStorage.getItem('sls2.total') }));
await p.click('#end-home');
await p.waitForTimeout(150);
const titleAfter = await p.evaluate("!document.getElementById('title').classList.contains('hidden')");
const grid = await p.evaluate(() => Array.from(document.querySelectorAll('.lv')).map(b=>b.className).slice(0,3));
await p.screenshot({ path:'/mnt/tos/workspace/.scratch/guizang3/silkline-swing/title-progress.png' });
// fail panel on a fresh level
await p.evaluate(() => { G.startLevel(3); G.setShards(1); G.forceFail('abyss'); });
await p.waitForTimeout(200);
await p.screenshot({ path:'/mnt/tos/workspace/.scratch/guizang3/silkline-swing/end-fail.png' });
const fail = await p.evaluate('G.state()');
await p.evaluate(() => { localStorage.clear(); });
console.log(JSON.stringify({ win:{mode:win.mode,totalStars:win.totalStars,unlocked:win.unlocked,best:win.best}, store, titleAfter, grid, fail:{mode:fail.mode}, logs }, null, 2));
await b.close();
