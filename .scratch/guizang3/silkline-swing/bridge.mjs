import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const b = await chromium.launch({ headless: true, executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox','--use-gl=swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const logs=[]; p.on('console',m=>{if(m.type()==='error'||m.type()==='warning')logs.push(m.type()+': '+m.text())}); p.on('pageerror',e=>logs.push('ERR '+e));
await p.setContent(`<!doctype html><html><body style="margin:0;background:#111"><iframe id="f" src="http://localhost:8621/silkline-swing/?level=1" style="width:1000px;height:620px;border:0"></iframe><script>window.msgs=[];addEventListener('message',e=>window.msgs.push(e.data));</script></body></html>`);
const frame = p.frames().find(f => f.url().includes('silkline-swing'));
await frame.waitForFunction('window.G && window.G.state');
await p.waitForTimeout(600);
const bridges = await frame.evaluate(() => ({goHome:typeof goHome, clickMore:typeof clickMore, dp_share:typeof dp_share, submit:typeof play68_submitScore, share:typeof show_share}));
await frame.evaluate('G.setShards(3); G.setTime(19); G.forceWin();');
await p.waitForTimeout(250);
const msgsWin = await p.evaluate('window.msgs');
// failure envelope
await frame.evaluate('G.startLevel(1); G.setShards(1); G.forceFail("abyss");');
await p.waitForTimeout(250);
const msgsAll = await p.evaluate('window.msgs');
console.log(JSON.stringify({bridges, winKinds: msgsWin.map(m=>m.type+':'+(m.payload&&m.payload.kind)), winSamples: msgsWin.slice(0,4), failEnvelope: msgsAll.filter(m=>m.payload&&m.payload.kind==='gameOver'), logs}, null, 2));
await b.close();
