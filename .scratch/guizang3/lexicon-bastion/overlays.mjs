import { createRequire } from 'module';
const require = createRequire('/tmp/pw/node_modules/');
const { chromium } = require('playwright');
const OUT='/mnt/tos/workspace/.scratch/guizang3/lexicon-bastion/';
const BASE='http://localhost:8622/lexicon-bastion/';
const b = await chromium.launch({ executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox','--use-gl=swiftshader'] });
const errs=[];
let p = await b.newPage({ viewport:{width:640,height:360}, deviceScaleFactor:2 });
p.on('console',m=>{if(['error','warning'].includes(m.type()))errs.push(m.text())}); p.on('pageerror',e=>errs.push(String(e)));
await p.goto(BASE+'?autostart=1&demo=1',{waitUntil:'load'});
await p.waitForTimeout(300);
await p.evaluate('window.G.forceGameOver()');
await p.waitForTimeout(250);
await p.screenshot({path:OUT+'end-640.png'});
await p.close();
p = await b.newPage({ viewport:{width:430,height:820}, isMobile:true, hasTouch:true });
p.on('console',m=>{if(['error','warning'].includes(m.type()))errs.push(m.text())}); p.on('pageerror',e=>errs.push(String(e)));
await p.goto(BASE,{waitUntil:'load'});
await p.tap('#startbtn');
await p.waitForTimeout(2300);
await p.screenshot({path:OUT+'mobile-play-enemies.png'});
await p.evaluate('window.G.fresh(3); window.G.setInk(120); window.G.clearWaveNow();');
await p.waitForTimeout(250);
await p.screenshot({path:OUT+'mobile-draft.png'});
await p.close();
console.log('ERRORS', JSON.stringify(errs));
await b.close();
